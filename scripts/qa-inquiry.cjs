const assert = require('node:assert/strict');
const fs = require('node:fs');
module.exports = async function checkInquiry(page, engine, results, axePath) {
  let apiMode = 'failure';
  const requests = [];
  await page.route('**/api/inquiry', async route => {
    requests.push(route.request().postDataJSON());
    if (apiMode === 'offline') return route.abort();
    return route.fulfill({status: apiMode === 'success' ? 200 : 502, contentType: 'application/json', body: JSON.stringify({ok: apiMode === 'success'})});
  });
  const submit = () => page.getByRole('button', {name: 'Request my quote', exact: true}).click();
  const audit = async name => {
    if (engine !== 'chromium') return;
    if (!await page.evaluate(() => typeof window.axe !== 'undefined')) await page.addScriptTag({path: axePath});
    const result = await page.evaluate(() => axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'best-practice']}}));
    results.accessibility.push({page: name, violations: result.violations.map(v => ({id: v.id, nodes: v.nodes.map(n => ({target: n.target, summary: n.failureSummary}))}))});
  };
  await page.goto('http://review.test/contact.html');
  assert.equal(await page.locator('#event-contact-form [required]').count(), 7);
  for (const name of ['address', 'postal', 'city', 'state', 'referral']) assert.equal(await page.locator(`[name="${name}"]`).count(), 0);
  await submit();
  assert.equal(await page.locator('[aria-invalid="true"]').count(), 7);
  assert.equal(await page.evaluate(() => document.activeElement.id), 'form-errors');
  await audit('contact-seven-required');
  await page.goto('http://review.test/contact.html?service=meeting-catering');
  assert.equal(await page.locator('#service').inputValue(), 'meeting-catering');
  const values = {name: 'QA Guest', email: 'qa@example.com', company: 'Example Office', date: '2027-06-20', location: 'Atlanta office', guests: '25'};
  for (const [name, value] of Object.entries(values)) await page.locator(`[name="${name}"]`).fill(value);
  await submit();
  await page.locator('#inquiry-review').waitFor({state: 'visible'});
  assert.equal(requests.length, 1, 'seven essential fields and blank optional fields should reach the API');
  for (const [key, value] of Object.entries(values)) assert.equal(requests[0][key], value);
  assert.equal(requests[0].service, 'meeting-catering');
  assert.equal(requests[0].phone, '');
  for (const key of ['address', 'postal', 'city', 'state', 'referral']) assert(!Object.hasOwn(requests[0], key));
  let draft = await page.locator('#prepared-inquiry').inputValue();
  for (const value of Object.values(values)) assert(draft.includes(value));
  assert(draft.includes('Meeting catering'));
  assert(!draft.includes('Address:'));
  await page.locator('.optional-inquiry summary').click();
  await page.locator('#phone').fill('12');
  await page.locator('.optional-inquiry summary').click();
  await submit();
  assert.equal(await page.locator('#phone').getAttribute('aria-invalid'), 'true');
  assert.equal(await page.locator('.optional-inquiry').evaluate(x => x.open), true, 'invalid optional field must be revealed');
  assert.equal(requests.length, 1, 'invalid phone must not be submitted');
  await page.locator('#phone').fill('');
  const optional = {start: '09:00', end: '12:00', budget: '$800–$1,200', details: 'Vegetarian options; setup access at 8 AM. <script>test</script>'};
  for (const [key, value] of Object.entries(optional)) await page.locator(`[name="${key}"]`).fill(value);
  apiMode = 'offline';
  await submit();
  await page.locator('#inquiry-review').waitFor({state: 'visible'});
  draft = await page.locator('#prepared-inquiry').inputValue();
  for (const value of Object.values(optional)) assert(draft.includes(value));
  assert(decodeURIComponent(await page.locator('#open-email-draft').getAttribute('href')).includes(values.email));
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: undefined}));
  await page.getByRole('button', {name: 'Copy inquiry', exact: true}).click();
  assert((await page.locator('#contact-form-status').innerText()).includes('Select and copy'));
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async text => {window.qaCopied = text;}}}));
  await page.getByRole('button', {name: 'Copy inquiry', exact: true}).click();
  assert.equal(await page.evaluate(() => window.qaCopied), draft);
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download draft'}).click();
  assert.equal(fs.readFileSync(await (await downloading).path(), 'utf8'), draft);
  await audit('contact-network-fallback');
  await page.locator('#guests').fill('30');
  assert.equal(await page.locator('#inquiry-review').isVisible(), false);
  await page.locator('#email').fill('not-an-email');
  await submit();
  assert.equal(await page.locator('#email').getAttribute('aria-invalid'), 'true');
  await page.locator('#email').fill(values.email);
  apiMode = 'success';
  await submit();
  await page.locator('#inquiry-sent').waitFor({state: 'visible'});
  assert.equal(await page.evaluate(() => document.activeElement.id), 'inquiry-sent');
  assert.equal(await page.locator('#event-contact-form').isVisible(), false);
  await audit('contact-success');
  results.form[engine] = {requiredFields: 7, preselection: true, removedBillingFields: true, emptyOptionalFieldsAccepted: true, invalidOptionalFieldsRevealed: true, apiFailureAndOfflineFallback: true, clipboardHandlerAndFallback: true, download: true, staleDraftReset: true, apiSuccess: true, externalSubmission: false};
};
