const assert = require('node:assert/strict');
module.exports = async function checkMenus(page, engine, results) {
  await page.goto('http://review.test/catering-menus.html#sample-boxed-lunches');
  assert.equal(await page.locator('#sample-boxed-lunches').evaluate(x => x.open), true);
  assert.equal(await page.getByText('Italian hoagie', {exact: true}).isVisible(), true);
  await page.locator('.menu-jump-links').getByRole('link', {name: 'Breakfast', exact: true}).click();
  assert.equal(await page.locator('#sample-breakfast').evaluate(x => x.open), true);
  assert.equal(await page.getByText('Banana & chocolate bread with whipped walnut butter', {exact: true}).isVisible(), true);
  const summary = page.locator('#sample-breakfast summary');
  await summary.focus(); await page.keyboard.press('Enter');
  assert.equal(await page.locator('#sample-breakfast').evaluate(x => x.open), false);
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#sample-breakfast').evaluate(x => x.open), true);
  await page.goto('http://review.test/corporate-catering.html');
  await page.getByRole('link', {name: 'Browse sample menu selections', exact: false}).click();
  await page.waitForURL('**/catering-menus.html#sample-corporate-lunches');
  assert.equal(await page.locator('#sample-corporate-lunches').evaluate(x => x.open), true);
  await page.goto('http://review.test/catering-details.html');
  assert.equal(await page.locator('table caption').innerText(), 'Planning notice by service');
  assert.equal(await page.locator('tbody tr').count(), 7);
  assert.equal(await page.getByText('10 people.', {exact: true}).isVisible(), true);
  await page.locator('.policy-jump').getByRole('link', {name: 'Dietary requests', exact: true}).click();
  assert.equal(new URL(page.url()).hash, '#dietary');
  assert.equal(await page.locator('.allergen-note').isVisible(), true);
  const footerLink = page.locator('.site-footer').getByRole('link', {name: 'Ordering & delivery', exact: true});
  assert.equal(await footerLink.getAttribute('href'), 'catering-details.html');
  results.menus ||= {};
  results.menus[engine] = {directCategoryLink: true, keyboardDisclosure: true, serviceToMenuLink: true, leadTimeTable: true, policyNavigation: true};
};
