const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
(async () => {
  const source = fs.readFileSync('scripts/worker-template.js', 'utf8').replace("import archive from './assets.bin';", 'const archive = new ArrayBuffer(0);').replace('__ASSET_MANIFEST__', '{}').replace('export default', 'globalThis.worker =');
  let upstreamMode = 'success';
  const sent = [];
  const context = {Response, URL, Uint8Array, console, fetch: async (url, options) => {
    sent.push({url, body: JSON.parse(options.body)});
    if (upstreamMode === 'offline') throw new Error('Mock network failure');
    return new Response('{}', {status: upstreamMode === 'success' ? 201 : 400});
  }};
  vm.createContext(context); vm.runInContext(source, context);
  const essential = {name: 'QA Guest', email: 'qa@example.com', company: 'Example Office', date: '2027-06-20', location: 'Atlanta', guests: '25', service: 'corporate-catering'};
  const invoke = data => context.worker.fetch(new Request('https://southerncrescenthospitality.com/api/inquiry', {method: 'POST', headers: {'Content-Type': 'application/json', Origin: 'https://southerncrescenthospitality.com'}, body: JSON.stringify(data)}));
  assert.equal((await invoke({})).status, 400);
  assert.equal((await invoke({...essential, service: '__proto__'})).status, 400);
  assert.equal((await invoke({...essential, email: 'invalid'})).status, 400);
  assert.equal((await invoke({...essential, guests: '1.5'})).status, 400);
  assert.equal(sent.length, 0);
  let result = await invoke(essential);
  assert.equal(result.status, 200);
  assert.equal((await result.json()).ok, true);
  const answers = JSON.parse(sent[0].body.answers);
  const values = answers.map(a => a.answer1);
  assert(values.includes(essential.email));
  assert(values.includes(essential.company));
  assert(values.includes('Corporate catering'));
  assert.equal(values.filter(x => x === 'Not collected at initial quote stage').length, 5);
  assert(values.includes('Not provided; reply by email'));
  assert(values.includes('To discuss'));
  const optional = {...essential, phone: '770-555-0100', start: '09:30', end: '13:00', budget: '1200', details: 'Vegetarian options requested.'};
  result = await invoke(optional); assert.equal(result.status, 200);
  const extra = JSON.parse(sent[1].body.answers).map(x => x.answer1);
  for (const value of ['770-555-0100', '9:30 AM', '1:00 PM', '$1200', optional.details]) assert(extra.includes(value));
  upstreamMode = 'failure'; assert.equal((await invoke(essential)).status, 502);
  upstreamMode = 'offline'; assert.equal((await invoke(essential)).status, 502);
  const before = sent.length;
  assert.equal((await invoke({...essential, website: 'spam'})).status, 200);
  assert.equal(sent.length, before);
  console.log('Short inquiry API: essential-only and optional-detail submissions, legacy Microsoft question mapping, invalid input rejection, upstream failure handling, and honeypot passed. All upstream submissions mocked; no emails sent.');
})().catch(error => {console.error(error); process.exit(1);});
